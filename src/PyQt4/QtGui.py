from PyQt5.QtCore import QStandardPaths

_SRC_DIR = os.path.dirname(os.path.dirname(__file__))
_QT5_QPIXMAP = QPixmap

def _resource_path(path):
    if not isinstance(path, str) or not path.startswith(":/"):
        return path
    resource = path[2:]
    if resource.startswith("Icons/Icons/"):
        resource = "GUI/Icons/" + resource[len("Icons/Icons/"):]
    elif resource.startswith("Icons/"):
        resource = "GUI/" + resource
    elif resource.startswith("buttons/GUI/"):
        resource = resource[len("buttons/"):]
    elif resource.startswith("heads/GUI/"):
        resource = resource[len("heads/"):]
    return os.path.join(_SRC_DIR, resource)

def QPixmap(*args):
    if args:
        args = (_resource_path(args[0]),) + args[1:]
    return _QT5_QPIXMAP(*args)

class QDesktopServices:
    DocumentsLocation = QStandardPaths.DocumentsLocation
    HomeLocation = QStandardPaths.HomeLocation
    DesktopLocation = QStandardPaths.DesktopLocation
    MusicLocation = QStandardPaths.MusicLocation
    MoviesLocation = QStandardPaths.MoviesLocation
    PicturesLocation = QStandardPaths.PicturesLocation
    TempLocation = QStandardPaths.TempLocation

    @staticmethod
    def storageLocation(location):
        paths = QStandardPaths.standardLocations(location)
        if paths:
            return paths[0]
        return QStandardPaths.writableLocation(location)

